const vars = (obj, prefix = "") => Object.entries(obj).map(([k, v]) => `--${prefix}${k}:${v};`).join("");
const zoneBlock = (theme) =>
  Object.entries(zones).map(([z, t]) => vars(t[theme], `${z}-`)).join("");

export function tokensCss() {
  const dark = zoneBlock("dark"), light = zoneBlock("light");
  // The zone classes copy a zone's tokens into the generic --bg/--ink/... names that components use.
  const zoneClasses = Object.keys(zones).map((z) => {
    const keys = Object.keys(zones[z].dark);
    return `.zone-${z}{${keys.map((k) => `--z-${k}:var(--${z}-${k})`).join(";")};background:var(--z-bg);color:var(--z-ink)}`;
  }).join("\n");
  return `/* Generated by scripts/build.mjs from scripts/palette.mjs. Do not edit by hand. */
@font-face{font-family:"Bricolage Grotesque";font-weight:600;font-style:normal;font-display:swap;src:url(../fonts/bricolage-grotesque-latin-600-normal.woff2) format("woff2")}
@font-face{font-family:Inter;font-weight:400;font-style:normal;font-display:swap;src:url(../fonts/inter-latin-400-normal.woff2) format("woff2")}
@font-face{font-family:Inter;font-weight:600;font-style:normal;font-display:swap;src:url(../fonts/inter-latin-600-normal.woff2) format("woff2")}
@font-face{font-family:"JetBrains Mono";font-weight:400;font-style:normal;font-display:swap;src:url(../fonts/jetbrains-mono-latin-400-normal.woff2) format("woff2")}
:root{color-scheme:dark light;
--font-head:"Bricolage Grotesque","Inter",system-ui,sans-serif;--font-body:Inter,system-ui,"Segoe UI",Roboto,Arial,sans-serif;--font-mono:"JetBrains Mono","SF Mono",Consolas,monospace;
--gutter:16px;--max:1120px;--r:10px;--dur:240ms;
${dark}}
@media (prefers-color-scheme:light){:root:not([data-theme=dark]){${light}}}
:root[data-theme=light]{${light}}
:root[data-theme=dark]{${dark}}
${zoneClasses}
`;
}

